"""Release-card text to runtime binding consistency matrix.

The exporter consumes this module instead of maintaining a second hand-written
inventory.  Every non-empty printed rules segment must have at least one
explicit binding, every emitted VM command must exist in the Python registry,
and callers may require exact parity with the peer (Godot) VM registry.
"""
from __future__ import annotations

from collections.abc import Iterable, Mapping
from pathlib import Path
import json
from typing import Any

from data.card_registry import CardRegistry
from data.deck_definitions import ALL_CARD_IDS
from engine.commands.descriptors import VM_COMMAND_DESCRIPTORS
from engine.commands.vm_contract import VM_IR_VERSION, validate_command_spec


MATRIX_FORMAT_VERSION = 1

SUPPORTED_ENERGY_HOOKS = frozenset({
    "ON_ATTACH",
    "ON_PRIZE_REVEALED",
    "AFTER_DAMAGE",
    "MODIFY_DAMAGE",
})
SUPPORTED_ENERGY_ACTIONS = frozenset({
    "provide_energy",
    "switch_with_active",
    "attach_to_benched_pokemon",
    "draw_cards",
    "modify_damage",
})

